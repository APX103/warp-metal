def runtime_symbol(name: str):
    """Resolve a host-runtime symbol lazily (bucket D, M1.2+)."""
    if host is None:
        raise RuntimeError(
            f"wp.{name} requires the warp-metal host runtime (M1.2), which is "
            f"not wired in frontend-only mode"
        )
    return getattr(host, name)


class _LazySymbol:
    """Deferred binding to a host-runtime symbol (upstream context.py name).

    Stands in for runtime-land classes/functions referenced by vendored
    frontend code: callable, attribute-forwarding, and usable in
    isinstance/issubclass checks once a host runtime is wired.
    """

    def __init__(self, name):
        self._name = name

    def __call__(self, *args, **kwargs):
        return runtime_symbol(self._name)(*args, **kwargs)

    def __getattr__(self, attr):
        return getattr(runtime_symbol(self._name), attr)

    def __instancecheck__(self, instance):
        return isinstance(instance, runtime_symbol(self._name))

    def __subclasscheck__(self, subclass):
        return issubclass(subclass, runtime_symbol(self._name))


