"""Generate docs/api-surface.md — the full public ``wp.*`` API surface of
warp-metal vs NVIDIA warp-lang 1.19.0.

Data: the three-layer conformance instrument (tools/conform.py) surface
layer — every ``wp.*`` symbol referenced by the vendored warp frontend's
own test corpus is checked for presence and exact signature match against
a golden dump taken from real warp-lang under the Newton venv.

    # 1. golden dump (Newton venv, real warp, CPU-only):
    env -u NEWTON_WARP_BACKEND <newton>/.venv/bin/python -I tools/conform.py \
        --dump-golden tools/golden_surface.json
    # 2. generate (warp-metal venv, initializes Metal):
    .venv/bin/python tools/gen_api_surface.py

The generated document states, per symbol: identical / tolerated /
mismatch / missing, grouped into the KEP-0001 bucket taxonomy, followed by
the hand-written semantic sections (numeric classes, fail-loud surface,
Non-Goals, Newton integration evidence).
"""

import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # for paths.py + conform
import conform  # noqa: E402
import paths  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "api-surface.md"
GOLDEN = Path(__file__).resolve().parent / "golden_surface.json"

BUCKET_TITLES = {
    "A": "Data types (`wp.float32`, `wp.vec3`, `wp.mat33`, generics, …)",
    "B": "Array types (`wp.array`, `wp.array2d`, …)",
    "C": "Kernel builtins (math, vector/matrix ops, atomics, IO, …)",
    "D": "Host functions & modules (`wp.launch`, `wp.clone`, `wp.Mesh`, …)",
    "E": "Tile ops (`wp.tile_load`, `wp.tile_sum`, `wp.launch_tiled`, …)",
    "F": "Native structures (`wp.Bvh`, `wp.Mesh`, `wp.HashGrid`, `wp.Volume`, …)",
    "G": "Adjoint / autodiff surface (Non-Goal)",
    "H": "Debug / random",
    "?": "Unclassified",
}

STATUS_ORDER = ["ok", "tolerated", "mismatch", "missing", "extra", "kernel_only"]
STATUS_LABEL = {
    "ok": "identical",
    "tolerated": "equivalent (documented)",
    "mismatch": "signature mismatch",
    "missing": "not implemented",
    "extra": "extra (harmless)",
    "kernel_only": "kernel-text only",
}

SEMANTIC_NOTES = {
    # (bucket, symbol-or-prefix): note appended in the table
}


def main() -> int:
    res = conform.run_surface(GOLDEN)

    by_bucket: dict[str, dict[str, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for row in res["rows"]:
        by_bucket[row["bucket"]][row["status"]].append(row)

    L: list[str] = []
    L.append("# warp-metal public API surface vs NVIDIA warp-lang")
    L.append("")
    L.append(f"Generated by `tools/gen_api_surface.py` — warp-metal "
             f"{res['warp_metal_version']} vs golden warp-lang {res['golden_warp_version']}.")
    L.append("")
    L.append("## Method")
    L.append("")
    L.append("warp-metal vendors the warp-lang 1.19.0 frontend verbatim and swaps the")
    L.append("backend (MSL over Adjoint SSA, ObjC++/Metal runtime). The public Python")
    L.append("surface is therefore *the frontend's own surface*: the conformance")
    L.append("instrument (`tools/conform.py`, three-layer ratchet) walks every")
    L.append(f"`wp.*` symbol the frontend corpus references — **{res['n_symbols']} symbols** —")
    L.append("and compares presence + exact signature against a golden dump from real")
    L.append("warp-lang 1.19.0. Signature identity is necessary but not sufficient:")
    L.append("numeric behavior is pinned separately by the corpus layer (CPU golden vs")
    L.append("Metal, tolerance-asserted per kernel, ratchet-only-up) and the")
    L.append("trajectory layer (per-step body_q diff, drift cap 0.15).")
    L.append("")
    L.append("## Summary")
    L.append("")
    L.append("| status | count | meaning |")
    L.append("|---|---|---|")
    for st in STATUS_ORDER:
        label = STATUS_LABEL[st]
        meaning = {
            "ok": "present, exact signature match",
            "tolerated": "signature differs, behavior-equivalent (reason in table)",
            "mismatch": "signature differs (each is a named finding)",
            "missing": "absent — import/attribute fails loud with a named error",
            "extra": "kernel-only upstream; harmless exported extra",
            "kernel_only": "kernel-text builtin (upstream also has no module attr)",
        }[st]
        L.append(f"| {label} | {sum(len(rows) for rows in (b.get(st, []) for b in by_bucket.values()))} | {meaning} |")
    L.append("")
    L.append(f"Bottom line: **{res['n_ok']} of {res['n_symbols']} symbols are signature-identical**; "
             f"{res['n_tolerated']} documented-equivalent; {res['n_mismatch']} mismatches and "
             f"{res['n_missing']} gaps, each with a named reason below.")
    L.append("")

    L.append("## Full symbol table")
    L.append("")
    L.append("Grouped by KEP-0001 bucket; every status is live data from the surface layer,")
    L.append("not a claim. `mismatch`/`missing` rows carry the reason where the instrument")
    L.append("records one.")
    L.append("")
    for bucket in sorted(by_bucket, key=lambda b: (b == "?", b)):
        L.append(f"### {BUCKET_TITLES.get(bucket, bucket)}")
        L.append("")
        sts = [st for st in STATUS_ORDER if by_bucket[bucket].get(st)]
        for st in sts:
            rows = sorted(by_bucket[bucket][st], key=lambda r: r["sym"])
            label = STATUS_LABEL[st]
            L.append(f"**{label} — {len(rows)}**")
            L.append("")
            if st == "ok":
                # compress: identical symbols as a flowing list, they are the bulk
                names = ", ".join(f"`{r['sym']}`" for r in rows)
                L.append(names)
            else:
                L.append("| symbol | detail |")
                L.append("|---|---|")
                for r in rows:
                    detail = ""
                    if st == "tolerated":
                        detail = conform.TOLERATED_MISMATCHES.get(r["sym"], "")
                    elif st == "mismatch":
                        detail = f"golden: `{r.get('golden_sig')}` / metal: `{r.get('sig')}`"
                    elif st == "missing":
                        detail = f"upstream kind: `{r.get('golden_kind')}`"
                    note = SEMANTIC_NOTES.get(r["sym"], "")
                    if note:
                        detail = f"{detail}; {note}" if detail else note
                    L.append(f"| `{r['sym']}` | {detail} |")
            L.append("")

    L.append("## Semantic deltas that signatures cannot show")
    L.append("")
    L.append("These are the places where warp-metal is *deliberately* not bit-identical")
    L.append("or cannot be, and what replaces the upstream behavior:")
    L.append("")
    L.append("1. **fp64 kernel types fail loud.** Metal exposes no fp64 on Apple")
    L.append("   Silicon. `float64`/`vec3d`/`mat63`-class kernel types raise a named")
    L.append("   TranslationError at compile time (host-side numpy fp64 interop is")
    L.append("   unaffected — arrays convert on the boundary). Upstream silently runs")
    L.append("   them on CUDA. The one accepted exemption (B1): the steel tiled")
    L.append("   solver's friction-patch fp64 accumulation is shim-branch fp32")
    L.append("   (KEP-0001 decision ⑤).")
    L.append("2. **Adjoint / Tape is a Non-Goal.** `requires_grad=True` allocation,")
    L.append("   `wp.Tape`, grad/adjoint codegen raise a named RuntimeError (fail loud")
    L.append("   at the earliest adjoint surface). Setting `requires_grad = False` is")
    L.append("   the plain-inference path and works (warp_nn Parameter).")
    L.append("3. **`warp.fem` / `warp.sparse` / kamino** import fails loud (Non-Goal;")
    L.append("   not ported). Examples in those families are named EXEMPT in the")
    L.append("   Newton smoke matrix.")
    L.append("4. **`wp.Volume` / NanoVDB** not implemented (Non-Goal); `wp.HashGrid`")
    L.append("   device surface is a named gap (fails loud, blocks particle-model")
    L.append("   `builder.finalize()`); OptiX-class features have no Metal equivalent")
    L.append("   and are permanently cut.")
    L.append("5. **Numeric tolerance classes** (corpus layer, rtol 1e-5 / atol 1e-6")
    L.append("   baseline): atomics reorder summation (looser per-kernel tolerance),")
    L.append("   `wp.inverse`/cholesky-family carry fp32 rounding deltas,")
    L.append("   cancellation-knife-edge fixtures compare against Metal being")
    L.append("   *closer* to fp64 than the fp32 CPU golden. 46/0/4 corpus + 3/3")
    L.append("   trajectory rows are the pinned evidence (capture sub-mode adds 27")
    L.append("   bitwise-identical replay rows).")
    L.append("6. **Texture sampling** is host-staging only (`wp.texture_sample` MSL")
    L.append("   lowering absent — fails loud).")
    L.append("")
    L.append("## Newton integration evidence (application layer)")
    L.append("")
    L.append("The black-box contract is exercised where it matters — Newton running")
    L.append("its real physics stack through `import warp` → `warp_metal`:")
    L.append("")
    L.append("| layer | evidence |")
    L.append("|---|---|")
    L.append("| Solvers | SolverXPBD + semi-implicit on `device=\"metal\"`; steel tiled solver (tile ops); SolverMuJoCo end-to-end (robot_cartpole all-strict 91/91, max\\|Δ\\|=1.669e-6); mujoco_warp sparse JTDAJ blocked plain-launch (robot_g1/omniwheel full pipeline) |")
    L.append("| Collision | primitive + mesh collision, BVH queries (SAH host build), heightfields |")
    L.append("| Battery | 406/406 unittest · phase0 10/10 · surface (this doc's data) · corpus 46/0/4 · trajectory 3/3 |")
    L.append("| Examples | Newton smoke matrix (phase4-smoke.md): selection_materials + robot_policy PASS end-to-end (2026-11-17); the remaining failing rows run their FULL pipelines (ur10 500-frame sim, ik_cube 2000-frame IK stack, g1 sparse-JTDAJ solve, omniwheel 500-frame balance) and fail only their own physics criteria — the infrastructure gate layer is clear |")
    L.append("| Capture/replay | ScopedCapture + capture_launch: 27/44 corpus rows bitwise == eager, whole-frame graph replay |")
    L.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"written: {OUT}")
    print(f"summary: {res['n_ok']} ok / {res['n_tolerated']} tolerated / {res['n_mismatch']} mismatch / "
          f"{res['n_missing']} missing / {res['n_extra']} extra / {res['n_kernel_only']} kernel-only")
    return 0


if __name__ == "__main__":
    sys.exit(main())
