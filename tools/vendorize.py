"""Regenerate ``src/warp_metal/frontend/`` from the pinned NVIDIA warp source.

Usage::

    python3 tools/vendorize.py [--warp-src ~/work/nvidia-warp]

Requires ``~/work/nvidia-warp`` to be checked out at the pinned version
(v1.19.0; see ``src/warp_metal/compat.py``). Idempotent: every run rebuilds
the vendored tree from scratch.

Vendoring rules (KEP-0001, M0.2):

- Verbatim copies of pure-frontend modules with only mechanical rewrites:
  config, logger, module_registry, types, fabric, texture, deterministic,
  codegen, builtins.
- ``registry.py`` is extracted from ``warp/_src/context.py`` by an AST closure
  over the registration core (Function/add_builtin/builtin_functions/type_str
  + helpers). Runtime-land symbols (devices, launch, memory) are NOT vendored:
  they become placeholders or lazy ``runtime_symbol`` dispatches into the host
  runtime (warp-metal M1.2).
- Import rewrites (see REWRITE_RULES):
  - ``warp._src.<mod>`` chains -> ``_pkg.<mod>`` (lazy partial-init namespace;
    upstream relies on the same trick via ``import warp``)
  - ``warp._src.context.X`` -> ``_pkg.registry.X`` (context.py split: frontend
    core -> registry.py; runtime hub -> host runtime)
  - ``from warp._src.<mod> import ...`` -> relative imports (acyclic-safe only)
  - exported-builtin / host-runtime calls (``warp.add``, ``warp.launch`` ...)
    -> ``_registry.runtime_symbol("<name>")(...)`` (lazy, raises a clear error
    when no host runtime is wired)
  - ``setattr(warp, key, func)`` in add_builtin -> host-module export plumbing
- CUDA-only fast paths (libmathdx LTO dispatch in builtins.py, nvrtc builds)
  are preserved verbatim but permanently dormant: ``registry.runtime.core
  .wp_is_mathdx_enabled()`` returns False and ``_build`` is a stub that raises
  on use, so every gated branch takes its documented CPU/no-MathDx fallback.
- fp16/bf16 literal conversion (upstream: warp.so runtime core) is replaced by
  numpy bit manipulation in the registry shim.
"""

