# (warp/_src/context.py), Apache-2.0, Copyright (c) 2022 NVIDIA CORPORATION &
# AFFILIATES. This module holds the FRONTEND registration core only (builtin
# registry, Function, type_str). The runtime hub (devices, launch, capture,
# module build/exec) is NOT vendored; references to it are placeholders or
# lazy dispatches into the warp-metal host runtime (M1.2+). Regenerated by
# tools/vendorize.py -- edit that, not this.
"""Warp frontend registration core (extracted from upstream context.py)."""

