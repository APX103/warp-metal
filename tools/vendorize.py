def find_warp_version(warp_dir: Path) -> str:
    version_md = (warp_dir.parent / "VERSION.md").read_text()
    return version_md.strip().splitlines()[0].strip()


def insert_banner(source: str, name: str, version: str) -> str:
    lines = source.splitlines(keepends=True)
    # keep leading comment block (SPDX header), insert banner after it
    i = 0
    while i < len(lines) and lines[i].startswith("#"):
        i += 1
    banner = BANNER.format(version=version, name=name).splitlines(keepends=True)
    return "".join(lines[:i]) + "".join(banner) + "".join(lines[i:])


def apply_rewrites(source: str, name: str) -> str:
    for pattern, repl in REWRITE_RULES:
        source = re.sub(pattern, repl, source)
    for pattern, repl in FILE_RULES.get(name, []):
        source = re.sub(pattern, repl, source)
    return source


